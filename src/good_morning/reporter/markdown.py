"""Markdown レポート生成（モーニングレターの骨子）

レポートは「ヘッダー → 各セクション → フッター」で組み立てる。
各セクションは独立して作り、失敗したセクションは「取得失敗」と表示して
レポート全体は止めない（失敗理由はログに残す。good_morning.sections 参照）。
"""

from dataclasses import dataclass, field
from datetime import datetime
from pathlib import Path

from good_morning.models import Article
from good_morning.paths import OUTPUTS_DIR
from good_morning.timeutil import JST, format_jst, weekday_ja

REPORT_TITLE = "モーニングレター"

DISCLAIMER = (
    "本レポートは情報提供を目的として機械的に生成したもので、投資助言ではありません。"
    "投資判断はご自身の責任で行ってください。"
)

STATUS_OK = "ok"
STATUS_FAILED = "failed"
STATUS_PENDING = "pending"


@dataclass
class Section:
    """レポートの1セクション分の結果"""

    key: str
    title: str
    status: str = STATUS_PENDING
    body: str = ""
    # ヘッダーの「データ基準時刻」に載せる行（例: "米国株・指数: NY終値（11/14）"）
    basis: list[str] = field(default_factory=list)
    # フッターの「データ出典」に載せる名前（例: "yfinance"）
    sources: list[str] = field(default_factory=list)
    # 未実装セクションの案内（例: "フェーズ1で実装予定"）
    note: str = ""


@dataclass
class ReportMeta:
    generated_at: datetime
    notices: list[str] = field(default_factory=list)


def format_report_date(date: datetime) -> str:
    """2026年11月17日（火） の形式にする"""
    date = date.astimezone(JST)
    return f"{date.strftime('%Y年%m月%d日')}（{weekday_ja(date)}）"


def render_header(meta: ReportMeta, sections: list[Section]) -> list[str]:
    lines = [
        f"# {REPORT_TITLE} {format_report_date(meta.generated_at)}",
        "",
        f"- 生成時刻: {format_jst(meta.generated_at)}",
    ]

    # 複数のセクションが同じ基準（例: NY終値）を出すので、重複を除いて出た順に並べる
    basis = list(dict.fromkeys(line for section in sections for line in section.basis))
    if basis:
        lines.append("- データ基準時刻:")
        lines.extend(f"  - {line}" for line in basis)

    for notice in meta.notices:
        lines.append(f"- ⚠ {notice}")

    lines.append("")
    return lines


def render_section(section: Section) -> list[str]:
    lines = [f"## {section.title}", ""]

    if section.status == STATUS_OK:
        lines.append(section.body.rstrip())
    elif section.status == STATUS_FAILED:
        lines.append("> 取得失敗（理由はログを参照）")
    else:
        note = f"（{section.note}）" if section.note else ""
        lines.append(f"> 未実装{note}")

    lines.append("")
    return lines


def render_footer(meta: ReportMeta, sections: list[Section]) -> list[str]:
    lines = ["---", "", DISCLAIMER, ""]

    sources: list[str] = []
    for section in sections:
        for source in section.sources:
            if source not in sources:
                sources.append(source)
    if sources:
        lines.extend([f"データ出典: {' / '.join(sources)}", ""])

    lines.append(f"*Generated by good-morning at {format_jst(meta.generated_at)}*")
    return lines


def render_report(sections: list[Section], meta: ReportMeta) -> str:
    lines = render_header(meta, sections)
    for section in sections:
        lines.extend(render_section(section))
    lines.extend(render_footer(meta, sections))
    return "\n".join(lines) + "\n"


def report_filename(date: datetime) -> str:
    """outputs/ に保存するファイル名（YYYY-MM-DD.md、JST の日付）"""
    return f"{date.astimezone(JST).strftime('%Y-%m-%d')}.md"


def save_report(content: str, date: datetime, output_dir: Path | None = None) -> Path:
    """レポートを outputs/YYYY-MM-DD.md に保存する（同じ日に再実行したら上書き）"""
    output_dir = output_dir or OUTPUTS_DIR
    output_dir.mkdir(parents=True, exist_ok=True)

    filepath = output_dir / report_filename(date)
    filepath.write_text(content, encoding="utf-8")
    return filepath


def format_article(article: Article) -> list[str]:
    """1記事をMarkdown形式にフォーマット

    aion から引き継いだもの。主要ニュースのセクションはフェーズ4でこれを作り直す
    （「Why it matters」→「暗号資産への示唆」）。
    """
    lines = []

    lines.append(f"### [{article.title}]({article.url})")
    lines.append("")

    pub_date = article.published.strftime("%Y-%m-%d") if article.published else "不明"
    lines.append(f"**{article.source}** | {pub_date}")
    lines.append("")

    if article.ai_summary:
        lines.append(article.ai_summary)
        lines.append("")

    if article.why_it_matters:
        lines.append(f"> **Why it matters**: {article.why_it_matters}")
        lines.append("")

    return lines
